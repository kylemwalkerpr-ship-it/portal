#!/usr/bin/env node
/**
 * Replace hardcoded "SEO Factory" boilerplate in Tldr with actual article content.
 * Runs from the portal directory so supabase-js is available.
 */
const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const { execSync } = require('child_process');
const { parse } = require('dotenv');

const env = parse(fs.readFileSync('.env.local', 'utf8'));
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_ANON_KEY, { auth: { autoRefreshToken: false, persistSession: false } });

const BOILERPLATE = 'This guide was generated by the SEO Factory from live Search Console demand. Verify every official rule against primary government sources before relying on it.';
const CASEWORKS = '../caseworks';

function markdownToTldrJsx(md) {
  const lines = md.split('\n');
  const parts = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const match = trimmed.match(/^- (.+)$/);
    if (match) {
      let text = match[1];
      text = text.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
      text = text.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
      parts.push(`        <p>${text}</p>`);
    }
  }
  return parts.join('\n');
}

async function main() {
  const files = execSync(`grep -rl "SEO Factory from live Search Console" ${CASEWORKS}/app/ --include="page.tsx" 2>/dev/null || true`, { encoding: 'utf8' })
    .trim().split('\n').filter(Boolean);

  console.log(`Found ${files.length} files with boilerplate\n`);

  let fixed = 0;
  for (const file of files) {
    const content = fs.readFileSync(file, 'utf8');
    
    const slugMatch = file.match(/app\/(?:us|uk|ca|au)\/([^/]+)\/page\.tsx/);
    if (!slugMatch) continue;
    const slug = slugMatch[1];
    
    const { data } = await sb.from('content_jobs')
      .select('id,title,content')
      .eq('slug', slug)
      .order('created_at', { ascending: false })
      .limit(1)
      .single();
    
    if (!data || !data.content) {
      console.log(`⚠️  ${file}: no content in DB for slug "${slug}"`);
      continue;
    }
    
    const bodyLines = data.content.split('\n');
    const idx60 = bodyLines.findIndex(l => /^## In 60 [Ss]econd/i.test(l));
    if (idx60 < 0) {
      console.log(`⚠️  ${file}: no "In 60 seconds" section`);
      continue;
    }
    
    let section = '';
    for (let i = idx60 + 1; i < bodyLines.length; i++) {
      if (/^## /.test(bodyLines[i])) break;
      section += bodyLines[i] + '\n';
    }
    
    const tldrJsx = markdownToTldrJsx(section.trim());
    if (!tldrJsx) {
      console.log(`⚠️  ${file}: empty "In 60 seconds" section`);
      continue;
    }
    
    const oldTldr = `      <Tldr title="In 60 seconds">\n        <p>${BOILERPLATE}</p>\n      </Tldr>`;
    const newTldr = `      <Tldr title="In 60 seconds">\n${tldrJsx}\n      </Tldr>`;
    
    if (content.includes(oldTldr)) {
      fs.writeFileSync(file, content.replace(oldTldr, newTldr));
      fixed++;
      console.log(`✅ ${file.replace(CASEWORKS + '/', '')}`);
    } else {
      console.log(`⚠️  ${file.replace(CASEWORKS + '/', '')}: pattern not found`);
    }
  }

  console.log(`\nFixed ${fixed} files`);
}

main().catch(console.error);
